//Switch EXpression Java
public class b88 {

    public static void main(String[] args) {

        int day = 2;
        String result;

        switch (day) {

            case 1:
                result = "Monday";
                break;
            case 2:
                result = "Tuesady";
                break;
            case 3:
                result = "Friday";
                break;
            default:
                result = "Invalid Day";
        }
        System.out.println(result);
    }
}
